// ─── התאמת "מילה שלמה" בעברית ────────────────────────────────────────────────
// ⚠️ ה-\b של JS *לא עובד* ליד אותיות עבריות — לכן בונים גבול מילה ידנית.
// לפני המילה: תחילת מחרוזת או תו שאינו אות/ספרה, ואחריו עד שתי אותיות שימוש
// (ו/ה/ל/ב/כ/מ/ש) כדי ש"לצהרון" / "בהמתנה" / "ולקייטנה" עדיין ייתפסו.
// אחרי המילה: תו שאינו אות/ספרה או סוף מחרוזת — כך ש"מתי" לא נתפס בתוך "רשמתי".
const WORD_CHARS      = 'א-תA-Za-z0-9'
const PREFIX_LETTERS  = 'ולבהכמש'

function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

const wholeWordCache = new Map<string, RegExp>()

export function matchesWholeWord(text: string, word: string): boolean {
  let re = wholeWordCache.get(word)
  if (!re) {
    re = new RegExp(
      `(^|[^${WORD_CHARS}])[${PREFIX_LETTERS}]{0,2}${escapeRegex(word)}([^${WORD_CHARS}]|$)`,
      'i'
    )
    wholeWordCache.set(word, re)
  }
  return re.test(text)
}

// צירוף מילים → התאמת תת-מחרוזת (הצירוף עצמו כבר מספיק ספציפי).
// מילה בודדת → מילה שלמה בלבד.
function matchKeyword(text: string, keyword: string): boolean {
  return keyword.includes(' ') ? text.includes(keyword) : matchesWholeWord(text, keyword)
}

