// מילות שאלה על לו"ז — 'מתי' כאן היא *מילה שלמה* (אחרת "רשמתי" היה מפעיל אותה)
const SCHEDULE_WORDS  = ['שעות', 'מתי', 'לו"ז', 'לוז', 'לוח זמנים', 'באיזה שעה', 'באיזו שעה']
// שאלת מחיר על המסגרת — קודמת לרישום ("כמה עולה הצהרון?" אינה בקשת רישום)
const COST_WORDS      = ['כמה עולה', 'כמה זה עולה', 'כמה משלמים', 'מחיר', 'עלות', 'כמה עולה החודש']
// עזיבה = ביטול, גם בלי המילה "ביטול" ("אני עובר לצהרון אחר", "לא ממשיכים בשנה הבאה")
const LEAVING_RE      = /עובר(ת)? ל|עוזב|מעביר(ה)? את הילד|לא ממשיכ/
const LEAVING_CONTEXT = ['צהרון', 'צהרונים', 'קייטנה', 'קייטנות', 'מסגרת']
// חג/חופשה + מסגרת = שאלת לו"ז ("יש צהרון בערב ראש השנה?") — קודם לרישום
const HOLIDAY_WORDS   = ['ראש השנה', 'כיפור', 'סוכות', 'חנוכה', 'פסח', 'שבועות', 'חג', 'חגים', 'חופש', 'חופשה']
const HOLIDAY_CONTEXT = ['צהרון', 'צהרונים', 'קייטנה', 'קייטנות', 'פתוח', 'פתוחים', 'סגור', 'סגורים', 'יש']

// ─── "סלט נושאים" ────────────────────────────────────────────────────────────
// הודעה שנוגעת בשלושה נושאים שונים (או נאום ארוך) אינה בקשה אחת — לנחש ממנה
// מסלול זה הימור. מחזירים 'לא_ידוע' וה-LLM שואל שאלת הבהרה.
// כוונות מאותה משפחה נספרות פעם אחת (תשלום/רישום), כדי לא לתפוס משפט תמים.
const INTENT_FAMILY: Array<[BotIntent, string]> = [
  ['רישום_צהרון', 'רישום'], ['רישום_קייטנה', 'רישום'],
  ['ביטול', 'ביטול'],
  ['שאלת_לוז', 'לוז'],
  ['איסוף_מוקדם', 'איסוף'],
  ['בדיקת_תשלום', 'תשלום'], ['אפשרויות_תשלום', 'תשלום'], ['כשל_תשלום', 'תשלום'],
  ['רשימת_המתנה', 'המתנה'],
]

function matchedFamilies(lowerText: string): number {
  const families = new Set<string>()
  for (const [intent, family] of INTENT_FAMILY) {
    if (intentKeywords[intent].some(kw => matchKeyword(lowerText, kw.toLowerCase()))) families.add(family)
  }
  return families.size
}

export function classifyIntent(text: string): BotIntent {
  const trimmed   = normalizeMessage(text).trim()
  const lowerText = trimmed.toLowerCase()

  // ספרה בודדת = בחירה מהתפריט (רק כשזו כל ההודעה)
  const digitIntent = DIGIT_INTENTS[trimmed]
  if (digitIntent) return digitIntent

  // ── הודעה ארוכה / רב-נושאית → לא מתחילים מסלול בניחוש ────────────────────
  // בקשת נציג מפורשת תמיד גוברת (היא חד-משמעית, גם בתוך נאום ארוך).
  const asksHuman = intentKeywords['בקשת_נציג'].some(kw => matchKeyword(lowerText, kw.toLowerCase()))
  if (!asksHuman) {
    const wordCount = trimmed.split(/\s+/).filter(Boolean).length
    if (wordCount > 40) return 'לא_ידוע'
    if (matchedFamilies(lowerText) >= 3) return 'לא_ידוע'
  }

  // "לבטל צהרון/קייטנה" → ביטול (לא רישום!) — אחרת המילה "צהרון" תפעיל רישום
  if (CANCEL_WORDS.some(w => matchKeyword(lowerText, w)) &&
      FRAMEWORK_WORDS.some(w => matchKeyword(lowerText, w))) {
    return 'ביטול'
  }

  // "אני עובר לצהרון אחר" / "לא ממשיכים בקייטנה" → ביטול (עזיבה בלי המילה ביטול)
  if (LEAVING_RE.test(lowerText) && LEAVING_CONTEXT.some(w => matchKeyword(lowerText, w))) {
    return 'ביטול'
  }

  // "יש צהרון בערב ראש השנה?" → שאלת לו"ז (לא רישום, שקודם לו בעדיפות)
  if (HOLIDAY_WORDS.some(w => matchKeyword(lowerText, w)) &&
      HOLIDAY_CONTEXT.some(w => matchKeyword(lowerText, w))) {
    return 'שאלת_לוז'
  }

  // "מה שעות הקייטנה?" → שאלת לו"ז (לא רישום לקייטנה, שקודם לו בעדיפות)
  if (SCHEDULE_WORDS.some(w => matchKeyword(lowerText, w)) &&
      FRAMEWORK_WORDS.some(w => matchKeyword(lowerText, w))) {
    return 'שאלת_לוז'
  }

  // "כמה עולה הצהרון?" → שאלת מחיר (לא רישום לצהרון, שקודם לו בעדיפות)
  if (COST_WORDS.some(w => matchKeyword(lowerText, w)) &&
      FRAMEWORK_WORDS.some(w => matchKeyword(lowerText, w))) {
    return 'בדיקת_תשלום'
  }

  // סדר עדיפות — כשל תשלום לפני בדיקת תשלום
  const priorityOrder: BotIntent[] = [
    'בקשת_נציג',
    'כשל_תשלום',
    'אפשרויות_תשלום',
    'רישום_קייטנה',
    'רישום_צהרון',
    'ביטול',
    'איסוף_מוקדם',
    'רשימת_המתנה',
    'שאלת_לוז',
    'בדיקת_תשלום',
    'שאלה_כללית',
    'לא_ידוע'
  ]

  for (const intent of priorityOrder) {
    const keywords = intentKeywords[intent]
    if (keywords.some(kw => matchKeyword(lowerText, kw.toLowerCase()))) {
      return intent
    }
  }

  return 'לא_ידוע'
}
